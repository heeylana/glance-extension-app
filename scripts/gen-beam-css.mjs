/**
 * The bubble's border beam without shipping React to every page. Renders the published
 * `border-beam` component (Jakub Antalik, MIT) once to static markup, keeps the <style> it
 * generates, and pins the instance id to "glance". `@property` rules do not register inside a
 * shadow root, so they go to a module the content script registers with CSS.registerProperty.
 *
 *   node scripts/gen-beam-css.mjs    # rewrites entrypoints/content/beam.generated.{css,ts}
 *
 * The bubble toggles `data-active` / `data-fading` on the element carrying `data-beam="glance"`.
 */
import { writeFileSync, readFileSync } from "node:fs";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { BorderBeam } from "border-beam";

const OPTIONS = { size: "md", colorVariant: "ocean", theme: "dark", borderRadius: 16 };
const version = JSON.parse(readFileSync(new URL("../node_modules/border-beam/package.json", import.meta.url), "utf8")).version;

const html = renderToStaticMarkup(createElement(BorderBeam, OPTIONS, createElement("div")));
const id = /data-beam="([^"]+)"/.exec(html)?.[1];
const raw = /<style>([\s\S]*?)<\/style>/.exec(html)?.[1];
if (!id || !raw) throw new Error("border-beam markup changed: no data-beam id or <style>");
const unescape = (s) => s.replace(/&quot;/g, '"').replace(/&#x27;/g, "'").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&amp;/g, "&");
let css = unescape(raw).split(id).join("glance");

const PROPERTY = /@property\s+(--[\w-]+)\s*\{\s*syntax:\s*"([^"]+)";\s*initial-value:\s*([^;]+);\s*inherits:\s*(true|false);\s*\}\s*/g;
const properties = [...css.matchAll(PROPERTY)].map((m) => ({ name: m[1], syntax: m[2], initialValue: m[3].trim(), inherits: m[4] === "true" }));
css = css.replace(PROPERTY, "").trim();

const banner = `Generated by scripts/gen-beam-css.mjs from border-beam@${version} (MIT, Jakub Antalik) with ${JSON.stringify(OPTIONS)}. Do not edit.`;
writeFileSync(new URL("../entrypoints/content/beam.generated.css", import.meta.url), `/* ${banner} */\n${css}\n`);
writeFileSync(
  new URL("../entrypoints/content/beam.generated.ts", import.meta.url),
  `// ${banner}\n// @property rules are ignored inside a shadow root; the bubble registers these on the document.\nexport const BEAM_PROPERTIES = ${JSON.stringify(properties, null, 2)} as const;\n`,
);
console.log(`border-beam@${version}: ${css.length} bytes of CSS, ${properties.length} properties`);
